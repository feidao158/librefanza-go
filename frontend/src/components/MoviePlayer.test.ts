import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import MoviePlayer from './MoviePlayer.vue'
import { i18n } from '../i18n'

const request = vi.hoisted(() => vi.fn())
vi.mock('../api/client', () => ({ api: request }))

describe('影片播放', () => {
  beforeEach(() => { request.mockReset() })
  it('按需检索并提示没有可播放来源', async () => {
    request.mockResolvedValue({ data: [] })
    const wrapper = mount(MoviePlayer, { props: { id: 'ABC-123' }, global: { plugins: [i18n] } })
    expect(request).not.toHaveBeenCalled()
    await wrapper.get('button').trigger('click')
    await flushPromises()
    expect(request).toHaveBeenCalledWith('/movies/ABC-123/playbacks')
    expect(wrapper.text()).toContain('未找到可播放的来源')
  })
  it('来源请求失败时展示错误状态', async () => {
    request.mockRejectedValue(new Error('source unavailable'))
    const wrapper = mount(MoviePlayer, { props: { id: 'ABC-123' }, global: { plugins: [i18n] } })
    await wrapper.get('button').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('播放来源不可用')
    expect(wrapper.find('a[href="https://jable.tv/videos/abc-123/"]').attributes('target')).toBe('_blank')
  })
  it('来源要求验证时说明原因并保留跳转', async () => {
    request.mockRejectedValue({ code: 'playback_verification_required' })
    const wrapper = mount(MoviePlayer, { props: { id: 'ABC-123' }, global: { plugins: [i18n] } })
    await wrapper.get('button').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('Jable 要求人工验证')
    expect(wrapper.find('a[href="https://jable.tv/videos/abc-123/"]').exists()).toBe(true)
  })
  it('切换影片后忽略尚未完成的旧请求', async () => {
    vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {})
    vi.spyOn(HTMLMediaElement.prototype, 'load').mockImplementation(() => {})
    let finish!: (value: unknown) => void
    request.mockReturnValue(new Promise(resolve => { finish = resolve }))
    const wrapper = mount(MoviePlayer, { props: { id: 'ABC-123' }, global: { plugins: [i18n] } })
    await wrapper.get('button').trigger('click')
    await wrapper.setProps({ id: 'START-639' })
    finish({ data: [] })
    await flushPromises()
    expect(wrapper.find('a[href="https://jable.tv/videos/start-639/"]').exists()).toBe(true)
    expect(wrapper.text()).not.toContain('未找到可播放的来源')
    vi.restoreAllMocks()
  })
  it('启动磁力播放并在关闭时释放会话', async () => {
    vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {})
    vi.spyOn(HTMLMediaElement.prototype, 'load').mockImplementation(() => {})
    vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue()
    request.mockResolvedValueOnce({ data: { token: 'session123', stream_url: '/api/v1/torrent-sessions/session123/stream', source_url: 'https://sukebei.nyaa.si/view/1', seeders: 20 } }).mockResolvedValue({ data: undefined })
    const wrapper = mount(MoviePlayer, { props: { id: 'ABC-123' }, global: { plugins: [i18n] } })
    await wrapper.get('[data-testid="torrent-play"]').trigger('click')
    await flushPromises()
    expect(wrapper.get('video').attributes('src')).toBe('/api/v1/torrent-sessions/session123/stream')
    expect(wrapper.text()).toContain('正在缓冲')
    await wrapper.get('video').trigger('playing')
    expect(wrapper.text()).not.toContain('正在缓冲')
    await wrapper.get('video').trigger('waiting')
    expect(wrapper.text()).toContain('正在缓冲')
    expect(wrapper.text()).toContain('20')
    await wrapper.get('[aria-label="关闭"]').trigger('click')
    expect(request).toHaveBeenCalledWith('/torrent-sessions/session123', expect.objectContaining({ method: 'DELETE' }))
    wrapper.unmount()
    vi.restoreAllMocks()
  })
  it('长时间缓冲时显示失败并允许重试', async () => {
    vi.useFakeTimers()
    vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {})
    vi.spyOn(HTMLMediaElement.prototype, 'load').mockImplementation(() => {})
    vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue()
    request.mockResolvedValue({ data: { token: 'session123', stream_url: '/stream', source_url: 'https://sukebei.nyaa.si/view/1', seeders: 2 } })
    const wrapper = mount(MoviePlayer, { props: { id: 'ABC-123' }, global: { plugins: [i18n] } })
    await wrapper.get('[data-testid="torrent-play"]').trigger('click')
    await flushPromises()
    await vi.advanceTimersByTimeAsync(75_000)
    expect(wrapper.text()).toContain('视频加载失败')
    expect(wrapper.text()).toContain('重试')
    wrapper.unmount()
    vi.useRealTimers()
    vi.restoreAllMocks()
  })
})
